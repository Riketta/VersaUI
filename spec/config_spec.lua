-- Specs for the pure configuration layer: defaults, parsing, clamping.
local Config = require("VersaUI.config")

describe("config defaults", function()
    it("returns disabled frame overrides at unit scale", function()
        local defaults = Config.GetDefaults()
        assert.is_false(defaults.tot.enabled)
        assert.equals(defaults.tot.scale, 1)
        assert.equals(defaults.tot.offsetX, 0)
        assert.equals(defaults.tot.offsetY, 0)
        assert.is_false(defaults.targetCastBar.enabled)
        assert.is_false(defaults.focusTot.enabled)
        assert.is_false(defaults.focusCastBar.enabled)
        assert.is_false(defaults.targetLevel.enabled)
        assert.is_false(defaults.focusLevel.enabled)
        assert.is_false(defaults.petCastBar.enabled)
        assert.is_true(defaults.tot.relativeToParent)
        assert.is_true(defaults.focusTot.relativeToParent)
    end)

    it("returns disabled toggles and neutral padding", function()
        local defaults = Config.GetDefaults()
        assert.is_false(defaults.petAurasOnTop)
        assert.is_false(defaults.factionColorDisabled)
        assert.is_false(defaults.hidePvpIcon)
        assert.is_false(defaults.hideFocusAuras)
        assert.is_false(defaults.barPadding.enabled)
        assert.equals(defaults.barPadding.paddingX, 2)
        assert.equals(defaults.barPadding.paddingY, 2)
        assert.is_false(defaults.mouseLookSpeed.enabled)
        assert.equals(defaults.mouseLookSpeed.yaw, 60)
        assert.equals(defaults.mouseLookSpeed.pitch, 30)
        assert.is_false(defaults.barTexture.enabled)
        assert.equals(defaults.barTexture.texture, "flat")
        assert.is_false(defaults.barTexture.healthClassColorEnabled)
        assert.is_false(defaults.barTexture.healthColorEnabled)
        assert.equals(defaults.barTexture.healthColorR, 1)
        assert.equals(defaults.barTexture.healthColorG, 0)
        assert.equals(defaults.barTexture.healthColorB, 0)
        assert.is_false(defaults.barTexture.manaColorEnabled)
        assert.equals(defaults.barTexture.manaColorR, 0)
        assert.equals(defaults.barTexture.manaColorG, 0.44)
        assert.equals(defaults.barTexture.manaColorB, 0.87)
    end)
end)

describe("config.ParseNumber", function()
    it("parses valid numbers including negatives", function()
        assert.equals(Config.ParseNumber("12", 0), 12)
        assert.equals(Config.ParseNumber("-40", 0), -40)
    end)

    it("falls back on invalid or missing input", function()
        assert.equals(Config.ParseNumber("abc", 7), 7)
        assert.equals(Config.ParseNumber("", 7), 7)
        assert.equals(Config.ParseNumber(nil, 7), 7)
    end)
end)

describe("config.NormalizeFrameOverride", function()
    it("clamps scale into limits", function()
        local settings = Config.NormalizeFrameOverride({ enabled = true, scale = 300, offsetX = 0, offsetY = 0 })
        assert.equals(settings.scale, Config.LIMITS.scaleMax)
    end)

    it("clamps offsets into limits", function()
        local settings = Config.NormalizeFrameOverride({ enabled = true, scale = 1, offsetX = -9000, offsetY = 9000 })
        assert.equals(settings.offsetX, Config.LIMITS.offsetMin)
        assert.equals(settings.offsetY, Config.LIMITS.offsetMax)
    end)

    it("fills missing fields with defaults and coerces enabled", function()
        local settings = Config.NormalizeFrameOverride({})
        assert.is_false(settings.enabled)
        assert.equals(settings.scale, 1)
        assert.equals(settings.offsetX, 0)
        assert.equals(settings.offsetY, 0)
        assert.is_true(settings.relativeToParent)
    end)

    it("keeps an already-valid settings table untouched", function()
        local settings = Config.NormalizeFrameOverride({ enabled = true, scale = 1.5, offsetX = 10, offsetY = -10 })
        assert.equals(settings.scale, 1.5)
        assert.equals(settings.offsetX, 10)
        assert.equals(settings.offsetY, -10)
    end)
end)

describe("config.NormalizePaddingOverride", function()
    it("clamps padding into limits", function()
        local settings = Config.NormalizePaddingOverride({ enabled = true, paddingX = -5, paddingY = 500 })
        assert.equals(settings.paddingX, Config.LIMITS.paddingMin)
        assert.equals(settings.paddingY, Config.LIMITS.paddingMax)
    end)
end)

describe("config.NormalizeMouseLookSpeed", function()
    it("fills missing fields with below-game-minimum defaults", function()
        local settings = Config.NormalizeMouseLookSpeed({})
        assert.is_false(settings.enabled)
        assert.equals(settings.yaw, 60)
        assert.equals(settings.pitch, 30)
        assert.is_true(settings.originalYaw == nil)
        assert.is_true(settings.originalPitch == nil)
    end)

    it("clamps speeds into limits", function()
        local settings = Config.NormalizeMouseLookSpeed({ enabled = true, yaw = 0, pitch = 99999 })
        assert.is_true(settings.enabled)
        assert.equals(settings.yaw, Config.LIMITS.mouseSpeedMin)
        assert.equals(settings.pitch, Config.LIMITS.mouseSpeedMax)
    end)

    it("keeps numeric originals and drops junk captures", function()
        local settings =
            Config.NormalizeMouseLookSpeed({ yaw = 60, pitch = 30, originalYaw = 180, originalPitch = "x" })
        assert.equals(settings.originalYaw, 180)
        assert.is_true(settings.originalPitch == nil)
    end)
end)

describe("config.NormalizeBarTexture", function()
    it("fills missing fields with the flat texture default", function()
        local settings = Config.NormalizeBarTexture({})
        assert.is_false(settings.enabled)
        assert.equals(settings.texture, "flat")
    end)

    it("coerces enabled strictly and drops junk texture ids", function()
        local settings = Config.NormalizeBarTexture({ enabled = "yes", texture = 42 })
        assert.is_false(settings.enabled)
        assert.equals(settings.texture, "flat")

        settings = Config.NormalizeBarTexture({ enabled = true, texture = 42 })
        assert.is_true(settings.enabled)
        assert.equals(settings.texture, "flat")
    end)

    it("keeps a valid texture id", function()
        local settings = Config.NormalizeBarTexture({ enabled = true, texture = "Solid" })
        assert.is_true(settings.enabled)
        assert.equals(settings.texture, "Solid")
    end)

    it("fills missing health color fields with the red default", function()
        local settings = Config.NormalizeBarTexture({})
        assert.is_false(settings.healthClassColorEnabled)
        assert.is_false(settings.healthColorEnabled)
        assert.equals(settings.healthColorR, 1)
        assert.equals(settings.healthColorG, 0)
        assert.equals(settings.healthColorB, 0)
    end)

    it("clamps the custom health color into 0..1 and coerces enabled", function()
        local settings = Config.NormalizeBarTexture({
            healthColorEnabled = "yes",
            healthColorR = 2,
            healthColorG = -1,
            healthColorB = "x",
        })
        assert.is_false(settings.healthColorEnabled)
        assert.equals(settings.healthColorR, 1)
        assert.equals(settings.healthColorG, 0)
        assert.equals(settings.healthColorB, 0)

        settings = Config.NormalizeBarTexture({
            healthColorEnabled = true,
            healthColorR = 0.25,
            healthColorG = 0.5,
            healthColorB = 0.75,
        })
        assert.is_true(settings.healthColorEnabled)
        assert.equals(settings.healthColorR, 0.25)
        assert.equals(settings.healthColorG, 0.5)
        assert.equals(settings.healthColorB, 0.75)
    end)

    it("clamps the custom mana color into 0..1 and coerces enabled", function()
        local settings = Config.NormalizeBarTexture({
            manaColorEnabled = "yes",
            manaColorR = -3,
            manaColorG = "x",
            manaColorB = 9,
        })
        assert.is_false(settings.manaColorEnabled)
        assert.equals(settings.manaColorR, 0)
        assert.equals(settings.manaColorG, 0.44)
        assert.equals(settings.manaColorB, 1)

        settings = Config.NormalizeBarTexture({
            manaColorEnabled = true,
            manaColorR = 0.1,
            manaColorG = 0.2,
            manaColorB = 0.3,
        })
        assert.is_true(settings.manaColorEnabled)
        assert.equals(settings.manaColorR, 0.1)
        assert.equals(settings.manaColorG, 0.2)
        assert.equals(settings.manaColorB, 0.3)
    end)
end)

describe("config.Normalize", function()
    it("fills a blank table with a complete, disabled config", function()
        local db = Config.Normalize({})
        assert.is_false(db.tot.enabled)
        assert.is_false(db.targetCastBar.enabled)
        assert.is_false(db.focusCastBar.enabled)
        assert.is_false(db.targetLevel.enabled)
        assert.is_false(db.focusLevel.enabled)
        assert.is_false(db.petCastBar.enabled)
        assert.is_false(db.petAurasOnTop)
        assert.is_false(db.factionColorDisabled)
        assert.is_false(db.hidePvpIcon)
        assert.is_false(db.hideFocusAuras)
        assert.is_false(db.barPadding.enabled)
        assert.is_false(db.mouseLookSpeed.enabled)
        assert.is_false(db.barTexture.enabled)
        assert.equals(db.barTexture.texture, "flat")
        assert.is_false(db.barTexture.healthClassColorEnabled)
        assert.is_false(db.barTexture.healthColorEnabled)
        assert.equals(db.barTexture.healthColorR, 1)
        assert.is_false(db.barTexture.manaColorEnabled)
        assert.equals(db.barTexture.manaColorB, 0.87)
    end)

    it("coerces saved values strictly to true booleans", function()
        local db = Config.Normalize({ petAurasOnTop = true, factionColorDisabled = "yes", hidePvpIcon = true })
        assert.is_true(db.petAurasOnTop)
        assert.is_false(db.factionColorDisabled)
        assert.is_true(db.hidePvpIcon)

        db = Config.Normalize({ hideFocusAuras = true })
        assert.is_true(db.hideFocusAuras)
        db = Config.Normalize({ hideFocusAuras = "yes" })
        assert.is_false(db.hideFocusAuras)

        db = Config.Normalize({ barTexture = { enabled = true, healthColorEnabled = true, healthColorR = 0.1 } })
        assert.is_true(db.barTexture.healthColorEnabled)
        assert.equals(db.barTexture.healthColorR, 0.1)

        db = Config.Normalize({ barTexture = { manaColorEnabled = true } })
        assert.is_true(db.barTexture.manaColorEnabled)
        assert.equals(db.barTexture.manaColorR, 0)

        db = Config.Normalize({ barTexture = { healthClassColorEnabled = "yes" } })
        assert.is_false(db.barTexture.healthClassColorEnabled)
        db = Config.Normalize({ barTexture = { healthClassColorEnabled = true } })
        assert.is_true(db.barTexture.healthClassColorEnabled)
    end)

    it("normalizes saved level overrides like any frame override", function()
        local db = Config.Normalize({ targetLevel = { enabled = true, scale = 99 }, focusLevel = { offsetY = 5000 } })
        assert.is_true(db.targetLevel.enabled)
        assert.equals(db.targetLevel.scale, Config.LIMITS.scaleMax)
        assert.equals(db.targetLevel.offsetX, 0)
        assert.is_false(db.focusLevel.enabled)
        assert.equals(db.focusLevel.offsetY, Config.LIMITS.offsetMax)
        assert.is_true(db.focusLevel.relativeToParent)
    end)
end)
